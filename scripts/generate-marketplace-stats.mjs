#!/usr/bin/env node

/**
 * Fetches public Visual Studio Marketplace statistics used by static pages.
 *
 * Output:
 * - src/content/marketplaceStats.json
 * - src/content/marketplaceStats.generated.ts
 */

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(__dirname, '..')
const OUTPUT_FILE = path.join(ROOT, 'src', 'content', 'marketplaceStats.json')
const TS_OUTPUT_FILE = path.join(ROOT, 'src', 'content', 'marketplaceStats.generated.ts')
const MARKETPLACE_QUERY_URL = 'https://marketplace.visualstudio.com/_apis/public/gallery/extensionquery'
const CODE_XR_ITEM_NAME = 'aMonteSl.code-xr'
const CODE_XR_SOURCE_URL = 'https://marketplace.visualstudio.com/items?itemName=aMonteSl.code-xr'
const FALLBACK_DOWNLOADS = 300

function roundDownloads(downloadCount) {
  const numericCount = Number(downloadCount)
  if (!Number.isFinite(numericCount) || numericCount < FALLBACK_DOWNLOADS) {
    return FALLBACK_DOWNLOADS
  }

  return Math.floor(numericCount / 100) * 100
}

function formatDisplayDownloads(downloadCount) {
  return `${roundDownloads(downloadCount)}+`
}

function readExistingStats() {
  if (!fs.existsSync(OUTPUT_FILE)) {
    return null
  }

  try {
    return JSON.parse(fs.readFileSync(OUTPUT_FILE, 'utf8'))
  } catch {
    return null
  }
}

function normalizeStatsForComparison(stats) {
  if (!stats?.codeXr) {
    return null
  }

  return {
    codeXr: {
      downloadCount: stats.codeXr.downloadCount,
      displayDownloads: stats.codeXr.displayDownloads,
      sourceUrl: stats.codeXr.sourceUrl,
    },
  }
}

function preserveTimestampWhenUnchanged(nextStats) {
  const existingStats = readExistingStats()
  const existingComparable = normalizeStatsForComparison(existingStats)
  const nextComparable = normalizeStatsForComparison(nextStats)

  if (
    existingStats?.codeXr?.updatedAt &&
    JSON.stringify(existingComparable) === JSON.stringify(nextComparable)
  ) {
    return {
      ...nextStats,
      codeXr: {
        ...nextStats.codeXr,
        updatedAt: existingStats.codeXr.updatedAt,
      },
    }
  }

  return nextStats
}

function writeFileIfChanged(filePath, content) {
  if (fs.existsSync(filePath) && fs.readFileSync(filePath, 'utf8') === content) {
    console.log(`Unchanged ${filePath}`)
    return false
  }

  fs.writeFileSync(filePath, content)
  console.log(`Generated ${filePath}`)
  return true
}

function createTypescriptModule(stats) {
  return `// This file is generated by scripts/generate-marketplace-stats.mjs.
// Do not edit manually.

export const marketplaceStats = ${JSON.stringify(stats, null, 2)} as const

export type MarketplaceStats = typeof marketplaceStats
`
}

function createFallbackStats(reason) {
  const existingStats = readExistingStats()
  if (existingStats?.codeXr?.downloadCount) {
    console.warn(`Marketplace stats fetch failed, keeping existing stats: ${reason}`)
    return existingStats
  }

  console.warn(`Marketplace stats fetch failed, using fallback stats: ${reason}`)
  return {
    codeXr: {
      downloadCount: FALLBACK_DOWNLOADS,
      displayDownloads: formatDisplayDownloads(FALLBACK_DOWNLOADS),
      updatedAt: new Date(0).toISOString(),
      sourceUrl: CODE_XR_SOURCE_URL,
    },
  }
}

async function fetchCodeXrStats() {
  const response = await fetch(MARKETPLACE_QUERY_URL, {
    method: 'POST',
    headers: {
      accept: 'application/json;api-version=7.2-preview.1',
      'content-type': 'application/json',
    },
    body: JSON.stringify({
      filters: [
        {
          criteria: [{ filterType: 7, value: CODE_XR_ITEM_NAME }],
          pageNumber: 1,
          pageSize: 1,
          sortBy: 0,
          sortOrder: 0,
        },
      ],
      assetTypes: [],
      flags: 914,
    }),
  })

  if (!response.ok) {
    throw new Error(`${response.status} ${response.statusText}`)
  }

  const data = await response.json()
  const extension = data?.results?.[0]?.extensions?.[0]
  const downloadStat = extension?.statistics?.find((stat) => stat.statisticName === 'downloadCount')
  const downloadCount = Number(downloadStat?.value)

  if (!Number.isFinite(downloadCount)) {
    throw new Error('downloadCount statistic not found')
  }

  return {
    codeXr: {
      downloadCount,
      displayDownloads: formatDisplayDownloads(downloadCount),
      updatedAt: new Date().toISOString(),
      sourceUrl: CODE_XR_SOURCE_URL,
    },
  }
}

async function writeMarketplaceStats() {
  console.log('Fetching marketplace stats...')

  let stats
  try {
    stats = preserveTimestampWhenUnchanged(await fetchCodeXrStats())
  } catch (error) {
    stats = createFallbackStats(error instanceof Error ? error.message : String(error))
  }

  writeFileIfChanged(OUTPUT_FILE, `${JSON.stringify(stats, null, 2)}\n`)
  writeFileIfChanged(TS_OUTPUT_FILE, createTypescriptModule(stats))
  console.log(`Code-XR downloads: ${stats.codeXr.displayDownloads}`)
}

await writeMarketplaceStats()
